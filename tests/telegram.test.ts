const enabled = process.env.RUN_DB_TESTS === '1';
const password = 'MaxCareDev-2026!';
const unique = () => `${Date.now()}${Math.floor(Math.random() * 100000)}`;
const chatId = () => unique().slice(-12);
const botToken = () => `${unique().slice(-9)}:AA${unique()}${unique()}`.slice(0, 50);

const messageUpdate = (updateId: number, chat: string, text: string) => Buffer.from(JSON.stringify({ update_id: updateId, message: { chat: { id: Number(chat), type: 'private' }, text, date: Math.floor(Date.now() / 1000) } }));
const buttonUpdate = (updateId: number, chat: string, data: string) => Buffer.from(JSON.stringify({ update_id: updateId, callback_query: { id: `cq${updateId}`, data, message: { chat: { id: Number(chat), type: 'private' } } } }));

/** A patient who prefers Telegram, whose organization has a bot, linked to a fresh chat. */
async function telegramScenario(options: { link?: boolean; preferTelegram?: boolean } = {}) {
  const s = await noticeScenario({ consent: true });
  const token = botToken();
  await s.agent.put('/api/v1/automation/telegram-account').send({ bot_token: token }).expect(200);
  const account = await withTenant(s.orgId, (tx) => tx.telegramAccount.findFirstOrThrow());
  const secret = decryptSecret(account.webhookSecretEnc);
  const fake = new FakeTelegramProvider();
  const template = await withTenant(s.orgId, (tx) => tx.messageTemplate.create({
    data: { organizationId: s.orgId, channel: 'telegram', kind: 'refill_notice', name: `tg-${unique()}`, body: 'Hola {{paciente}}, tu reposición en {{farmacia}} está por vencer.', attemptNumber: 1 },
  }));
  if (options.preferTelegram !== false) {
    await withTenant(s.orgId, (tx) => tx.patient.update({ where: { id: s.patientId }, data: { preferredChannel: 'telegram' } }));
  }
  const chat = chatId();
  const ingest = (rawBody: Buffer, headerSecret: string | undefined = secret) =>
    ingestTelegramWebhook({ key: account.webhookKey, secretHeader: headerSecret, rawBody, provider: fake });
  const newLink = async () => {
    const created = await s.agent.post(`/api/v1/patients/${s.patientId}/telegram-link`).expect(201);
    return { url: created.body.url as string, token: (created.body.url as string).split('start=')[1]! };
  };
  if (options.link !== false) {
    const { token: linkToken } = await newLink();
    const linked = await ingest(messageUpdate(Number(unique().slice(-8)), chat, `/start ${linkToken}`));
    expect(linked.linked).toBe(1);
  }
  const tasks = () => withTenant(s.orgId, (tx) => tx.task.findMany({ where: { patientId: s.patientId, autoGenerated: true } }));
  const cycleNow = () => withTenant(s.orgId, (tx) => tx.refillCycle.findFirstOrThrow({ where: { id: s.cycle.id } }));
  const link = () => withTenant(s.orgId, (tx) => tx.telegramLink.findFirst({ where: { patientId: s.patientId } }));
  const finish = async () => {
    await s.agent.delete('/api/v1/automation/telegram-account');
    await withTenant(s.orgId, (tx) => tx.messageTemplate.update({ where: { id: template.id }, data: { isActive: false } }));
    await s.cleanup();
  };
  return { ...s, token, secret, key: account.webhookKey, fake, chat, ingest, newLink, tasks, cycleNow, link, finish, telegramTemplateId: template.id };
}

describe.skipIf(!enabled)('Telegram bot account', () => {
  it('connects a bot, keeps the token and the webhook secret encrypted and never returns them', async () => {
    const s = await noticeScenario({ consent: false });
    try {
      const token = botToken();
      const saved = await s.agent.put('/api/v1/automation/telegram-account').send({ bot_token: token }).expect(200);
      expect(saved.body).toMatchObject({ connected: true });
      expect(saved.body.bot_username).toMatch(/^fake_[0-9a-f]{8}_bot$/);
      expect(JSON.stringify(saved.body)).not.toContain(token);
      expect(await s.agent.get('/api/v1/automation/telegram-account').expect(200)).toMatchObject({ body: { connected: true } });
      const row = await withTenant(s.orgId, (tx) => tx.telegramAccount.findFirstOrThrow());
      expect(row.botTokenEnc.startsWith('v1:')).toBe(true);
      expect(row.botTokenEnc).not.toContain(token.split(':')[1]!);
      expect(row.webhookSecretEnc.startsWith('v1:')).toBe(true);
      expect(row.webhookKey).toMatch(/^[0-9a-f]{48}$/);

      await s.agent.delete('/api/v1/automation/telegram-account').expect(204);
      expect((await s.agent.get('/api/v1/automation/telegram-account').expect(200)).body.connected).toBe(false);
    } finally { await s.cleanup(); }
  });

  it('rejects a token that is not from BotFather and limits the endpoint to owners and admins', async () => {
    const s = await noticeScenario({ consent: false });
    try {
      await s.agent.put('/api/v1/automation/telegram-account').send({ bot_token: 'not-a-token' }).expect(400);
      const operator = request.agent(app);
      await operator.post('/api/auth/sign-in/email').send({ email: 'operator.b@maxcare.test', password }).expect(200);
      await operator.get('/api/v1/automation/telegram-account').expect(403);
      await operator.put('/api/v1/automation/telegram-account').send({ bot_token: botToken() }).expect(403);
      await operator.delete('/api/v1/automation/telegram-account').expect(403);
    } finally { await s.cleanup(); }
  });

  it('refuses a bot already connected to another organization', async () => {
    const a = request.agent(app);
    await a.post('/api/auth/sign-in/email').send({ email: 'owner.a@maxcare.test', password }).expect(200);
    const b = request.agent(app);
    await b.post('/api/auth/sign-in/email').send({ email: 'owner.b@maxcare.test', password }).expect(200);
    const token = botToken();
    try {
      await a.put('/api/v1/automation/telegram-account').send({ bot_token: token }).expect(200);
      await b.put('/api/v1/automation/telegram-account').send({ bot_token: token }).expect(409);
    } finally {
      await a.delete('/api/v1/automation/telegram-account');
      await b.delete('/api/v1/automation/telegram-account');
    }
  });
});

describe.skipIf(!enabled)('linking a patient chat', () => {
  it('needs a connected bot, then links only the chat that opens the single-use link', async () => {
    const s = await noticeScenario({ consent: true });
    try {
      await s.agent.post(`/api/v1/patients/${s.patientId}/telegram-link`).expect(409);
    } finally { await s.cleanup(); }

    const t = await telegramScenario({ link: false });
    try {
      const { url, token } = await t.newLink();
      expect(url).toMatch(/^https:\/\/t\.me\/fake_[0-9a-f]{8}_bot\?start=[A-Za-z0-9_-]{20,}$/);
      const row = await withTenant(t.orgId, (tx) => tx.telegramLinkToken.findFirstOrThrow({ where: { patientId: t.patientId } }));
      expect(row.tokenHash).not.toContain(token);

      const linked = await t.ingest(messageUpdate(1001, t.chat, `/start ${token}`));
      expect(linked).toMatchObject({ status: 200, linked: 1 });
      expect((await t.link())?.chatId).toBe(t.chat);
      expect(t.fake.service.at(-1)!.text).toContain('vinculado');

      // The same link in another chat does nothing.
      const stranger = chatId();
      const second = await t.ingest(messageUpdate(1002, stranger, `/start ${token}`));
      expect(second.linked).toBe(0);
      expect((await t.link())?.chatId).toBe(t.chat);
      expect(t.fake.service.at(-1)).toMatchObject({ chatId: stranger });
      expect(t.fake.service.at(-1)!.text).toContain('ya no es válido');

      const status = await t.agent.get(`/api/v1/patients/${t.patientId}/telegram`).expect(200);
      expect(status.body).toMatchObject({ bot_connected: true, linked: true });
      await t.agent.delete(`/api/v1/patients/${t.patientId}/telegram`).expect(204);
      expect(await t.link()).toBeNull();
    } finally { await t.finish(); }
  });

  it('rejects an expired or unknown link and explains a bare /start with a fixed text', async () => {
    const t = await telegramScenario({ link: false });
    try {
      const { token } = await t.newLink();
      await withTenant(t.orgId, (tx) => tx.telegramLinkToken.updateMany({ where: { patientId: t.patientId }, data: { expiresAt: new Date(Date.now() - 1000) } }));
      expect((await t.ingest(messageUpdate(2001, t.chat, `/start ${token}`))).linked).toBe(0);
      expect(await t.link()).toBeNull();
      await t.ingest(messageUpdate(2002, t.chat, '/start nope-nope-nope'));
      expect(t.fake.service.at(-1)!.text).toContain('ya no es válido');
      await t.ingest(messageUpdate(2003, t.chat, '/start'));
      expect(t.fake.service.at(-1)!.text).toContain('enlace que te dio la farmacia');
      // No reply was stored for any of these.
      const stored = await withTenant(t.orgId, (tx) => tx.whatsappInbound.count({ where: { channel: 'telegram', fromChatId: t.chat } }));
      expect(stored).toBe(0);
    } finally { await t.finish(); }
  });

  it('authenticates the webhook by its key and its secret header', async () => {
    const t = await telegramScenario({ link: false });
    try {
      const body = JSON.stringify({ update_id: Number(unique().slice(-8)), message: { chat: { id: Number(t.chat), type: 'private' }, text: 'hola' } });
      const post = (key: string, secret?: string) => {
        const req = request(app).post(`/webhooks/telegram/${key}`).set('Content-Type', 'application/json');
        return (secret === undefined ? req : req.set('X-Telegram-Bot-Api-Secret-Token', secret)).send(body);
      };
      await post('0'.repeat(48), t.secret).expect(404);
      await post(t.key).expect(401);
      await post(t.key, 'wrong-secret').expect(401);
      expect(await withTenant(t.orgId, (tx) => tx.whatsappInbound.count({ where: { fromChatId: t.chat } }))).toBe(0);
      await post(t.key, t.secret).expect(200);
      expect(await withTenant(t.orgId, (tx) => tx.whatsappInbound.count({ where: { fromChatId: t.chat } }))).toBe(1);
    } finally { await t.finish(); }
  });
});

describe.skipIf(!enabled)('sending notices through Telegram', () => {
  it('sends the planned message to the linked chat with the two buttons, only first name and pharmacy', async () => {
    const t = await telegramScenario();
    try {
      await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
      const planned = await t.plan();
      const outbox = planned.rows[0]!;
      expect(outbox).toMatchObject({ channel: 'telegram', status: 'pending' });

      const result = await sendNotice({ organizationId: t.orgId, outboxId: outbox.id, provider: new FakeProvider(), telegram: t.fake, queue: recordingQueue().queue, now: insideWindow() });
      expect(result).toEqual({ outcome: 'sent' });
      expect(t.fake.sent).toHaveLength(1);
      const sent = t.fake.sent[0]!;
      expect(sent.chatId).toBe(t.chat);
      expect(sent.text).toMatch(/^Hola Fictional, tu reposición en .+ está por vencer\.$/);
      expect(sent.text).not.toContain('Fictional plan med');
      expect(sent.buttons?.map((b) => b.callbackData)).toEqual(['confirm', 'need_help']);

      const row = await withTenant(t.orgId, (tx) => tx.outboxMessage.findFirstOrThrow({ where: { id: outbox.id } }));
      expect(row.status).toBe('sent');
      expect(row.providerMessageId).toMatch(/^tg:/);
      expect(await t.cycleNow()).toMatchObject({ status: 'notified', noticeAttempts: 1 });

      const conversation = await t.agent.get(`/api/v1/patients/${t.patientId}/messages`).expect(200);
      expect(conversation.body.data[0]).toMatchObject({ kind: 'notice', channel: 'telegram' });
    } finally { await t.finish(); }
  });

  it('falls back to WhatsApp when the patient prefers Telegram but never linked a chat', async () => {
    const t = await telegramScenario({ link: false });
    try {
      await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
      const planned = await t.plan();
      expect(planned.rows[0]).toMatchObject({ channel: 'whatsapp' });
    } finally { await t.finish(); }
  });

  it('asks staff to call when neither channel can reach the patient', async () => {
    const t = await telegramScenario({ link: false });
    try {
      await withTenant(t.orgId, (tx) => tx.patient.update({ where: { id: t.patientId }, data: { phoneHasWhatsapp: false } }));
      await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
      const planned = await t.plan();
      expect(planned.rows).toHaveLength(0);
      expect((await t.tasks()).filter((task) => task.type === 'call')).toHaveLength(1);
    } finally { await t.finish(); }
  });

  it('cancels instead of sending when the link was removed after planning', async () => {
    const t = await telegramScenario();
    try {
      await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
      const planned = await t.plan();
      await t.agent.delete(`/api/v1/patients/${t.patientId}/telegram`).expect(204);
      const result = await sendNotice({ organizationId: t.orgId, outboxId: planned.rows[0]!.id, provider: new FakeProvider(), telegram: t.fake, queue: recordingQueue().queue, now: insideWindow() });
      expect(result.outcome).toBe('not_claimed');
      expect(t.fake.sent).toHaveLength(0);
    } finally { await t.finish(); }
  });

  it('forgets the link and asks staff to call when the patient blocked the bot (403)', async () => {
    const t = await telegramScenario();
    try {
      await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
      const planned = await t.plan();
      t.fake.failWith = new MessagingError('blocked', true, 'tg_403');
      const result = await sendNotice({ organizationId: t.orgId, outboxId: planned.rows[0]!.id, provider: new FakeProvider(), telegram: t.fake, queue: recordingQueue().queue, now: insideWindow() });
      expect(result).toEqual({ outcome: 'failed', reason: 'tg_403' });
      expect(await t.link()).toBeNull();
      const calls = (await t.tasks()).filter((task) => task.type === 'call');
      expect(calls).toHaveLength(1);
      expect(calls[0]!.title).toContain('Telegram no disponible');
    } finally { await t.finish(); }
  });

  it('never sends through Telegram without consent', async () => {
    const t = await telegramScenario();
    try {
      await withTenant(t.orgId, (tx) => tx.patient.update({ where: { id: t.patientId }, data: { reminderConsent: false } }));
      await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
      const planned = await t.plan();
      expect(planned.rows).toHaveLength(0);
      expect(t.fake.sent).toHaveLength(0);
    } finally { await t.finish(); }
  });

  it('does not offer a test send for Telegram templates', async () => {
    const t = await telegramScenario();
    try {
      const response = await t.agent.post(`/api/v1/message-templates/${t.telegramTemplateId}/test-send`).send({ phone: '8095550123' }).expect(409);
      expect(response.body.error.code).toBe('TEST_SEND_UNSUPPORTED');
    } finally { await t.finish(); }
  });
});

describe.skipIf(!enabled)('replies through Telegram', () => {
  async function notified() {
    const t = await telegramScenario();
    await t.setAutomation({ automation_enabled: true, automation_dry_run: false });
    const planned = await t.plan();
    await sendNotice({ organizationId: t.orgId, outboxId: planned.rows[0]!.id, provider: new FakeProvider(), telegram: t.fake, queue: recordingQueue().queue, now: insideWindow() });
    const notice = () => withTenant(t.orgId, (tx) => tx.notice.findFirstOrThrow({ where: { cycleId: t.cycle.id } }));
    return { ...t, notice };
  }

  it('confirms the cycle on the Confirm button and dismisses the spinner', async () => {
    const t = await notified();
    try {
      const result = await t.ingest(buttonUpdate(Number(unique().slice(-8)), t.chat, 'confirm'));
      expect(result.stored).toBe(1);
      expect(t.fake.answered).toHaveLength(1);
      const summary = await processInbound({ organizationId: t.orgId });
      expect(summary.confirmed).toBe(1);
      expect((await t.cycleNow()).status).toBe('confirmed');
      expect((await t.notice()).status).toBe('replied');
    } finally { await t.finish(); }
  });

  it('stores free text, stops reminders and asks staff to review, without answering', async () => {
    const t = await notified();
    try {
      await t.ingest(messageUpdate(Number(unique().slice(-8)), t.chat, 'Paso mañana por la medicina'));
      const summary = await processInbound({ organizationId: t.orgId });
      expect(summary.free_text).toBe(1);
      expect((await t.cycleNow()).status).toBe('notified');
      expect((await t.tasks()).map((task) => task.title)).toEqual([expect.stringContaining('Revisar respuesta')]);
      // Nothing was sent back besides the one notice.
      expect(t.fake.sent).toHaveLength(1);
      expect(t.fake.service.filter((item) => item.text.includes('mañana'))).toHaveLength(0);
    } finally { await t.finish(); }
  });

  it('revokes consent on /stop', async () => {
    const t = await notified();
    try {
      await t.ingest(messageUpdate(Number(unique().slice(-8)), t.chat, '/stop'));
      const summary = await processInbound({ organizationId: t.orgId });
      expect(summary.opt_out).toBe(1);
      const patient = await withTenant(t.orgId, (tx) => tx.patient.findFirstOrThrow({ where: { id: t.patientId } }));
      expect(patient.reminderConsent).toBe(false);
    } finally { await t.finish(); }
  });

  it('stores an update only once when Telegram delivers it twice', async () => {
    const t = await notified();
    try {
      const raw = messageUpdate(Number(unique().slice(-8)), t.chat, 'hola');
      await t.ingest(raw);
      await t.ingest(raw);
      expect(await withTenant(t.orgId, (tx) => tx.whatsappInbound.count({ where: { fromChatId: t.chat } }))).toBe(1);
    } finally { await t.finish(); }
  });

  it('never assigns a chat linked only in another organization', async () => {
    const t = await notified();
    const agentA = request.agent(app);
    await agentA.post('/api/auth/sign-in/email').send({ email: 'owner.a@maxcare.test', password }).expect(200);
    const orgA = (await agentA.get('/api/v1/me').expect(200)).body as { organization: { id: string }; branches: { id: string }[] };
    try {
      const outsider = (await agentA.post('/api/v1/patients').send({ primaryBranchId: orgA.branches[0]!.id, fullName: `Fictional Outsider ${unique()}` }).expect(201)).body.patient as { id: string };
      const foreignChat = chatId();
      await withTenant(orgA.organization.id, (tx) => tx.telegramLink.create({ data: { organizationId: orgA.organization.id, patientId: outsider.id, chatId: foreignChat } }));

      await t.ingest(messageUpdate(Number(unique().slice(-8)), foreignChat, 'hola'));
      const summary = await processInbound({ organizationId: t.orgId });
      expect(summary.unassigned).toBeGreaterThanOrEqual(1);
      const row = await withTenant(t.orgId, (tx) => tx.whatsappInbound.findFirstOrThrow({ where: { fromChatId: foreignChat } }));
      expect(row.processedAt).not.toBeNull();
      expect(row.patientId).toBeNull();
      expect(await withTenant(orgA.organization.id, (tx) => tx.activity.count({ where: { patientId: outsider.id, type: 'notice' } }))).toBe(0);
    } finally { await t.finish(); }
  });

  it('leaves a chat shared by two patients unassigned for staff to decide', async () => {
    const t = await notified();
    try {
      const patient = await withTenant(t.orgId, (tx) => tx.patient.findFirstOrThrow({ where: { id: t.patientId } }));
      const sibling = await withTenant(t.orgId, (tx) => tx.patient.create({
        data: { organizationId: t.orgId, primaryBranchId: patient.primaryBranchId, fullName: 'Fictional Sibling', createdBy: patient.createdBy },
      }));
      await withTenant(t.orgId, (tx) => tx.telegramLink.create({ data: { organizationId: t.orgId, patientId: sibling.id, chatId: t.chat } }));
      await t.ingest(messageUpdate(Number(unique().slice(-8)), t.chat, 'hola'));
      expect((await processInbound({ organizationId: t.orgId })).unassigned).toBeGreaterThanOrEqual(1);
      const shared = await withTenant(t.orgId, (tx) => tx.whatsappInbound.findFirstOrThrow({ where: { fromChatId: t.chat }, orderBy: { receivedAt: 'desc' } }));
      expect(shared.patientId).toBeNull();
      expect((await t.cycleNow()).status).toBe('notified');
    } finally { await t.finish(); }
  });
});
