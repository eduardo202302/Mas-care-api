const unique = () => `${Date.now()}${Math.floor(Math.random() * 100000)}`;

async function loginAs(role: string) {
  const agent = request.agent(app);
  await agent.post('/api/auth/sign-in/email').send({ email: `${role}.b@maxcare.test`, password }).expect(200);
  return agent;
}

/** A planned (pending) message for a fresh patient, with automation fully on. */
async function pending() {
  const s = await noticeScenario({ consent: true });
  await s.setAutomation({ automation_enabled: true, automation_dry_run: false });
  const planned = await s.plan();
  const outbox = planned.rows[0]!;
  const reload = () => withTenant(s.orgId, (tx) => tx.outboxMessage.findFirstOrThrow({ where: { id: outbox.id } }));
  return { ...s, outbox, reload };
}

describe.skipIf(!enabled)('prescription review', () => {
  const expire = (s: Awaited<ReturnType<typeof noticeScenario>>) =>
    withTenant(s.orgId, (tx) => tx.treatment.update({ where: { id: s.treatmentId }, data: { prescriptionExpiresOn: new Date(Date.now() - 2 * 86_400_000) } }));
  const counts = (s: Awaited<ReturnType<typeof noticeScenario>>) => withTenant(s.orgId, async (tx) => ({
    incidents: await tx.incident.count({ where: { treatmentId: s.treatmentId, type: 'prescription_expired' } }),
    tasks: await tx.task.count({ where: { treatmentId: s.treatmentId, type: 'renew_prescription' } }),
  }));

  it('creates one incident and one renewal task, and nothing more on a rerun', async () => {
    const s = await noticeScenario({ consent: true });
    try {
      await expire(s);
      await s.setAutomation({ automation_enabled: true, automation_dry_run: false });
      await reviewPrescriptions({ organizationId: s.orgId });
      await reviewPrescriptions({ organizationId: s.orgId });
      expect(await counts(s)).toEqual({ incidents: 1, tasks: 1 });
      const incident = await withTenant(s.orgId, (tx) => tx.incident.findFirstOrThrow({ where: { treatmentId: s.treatmentId, type: 'prescription_expired' } }));
      expect(incident.autoGenerated).toBe(true);
    } finally { await s.cleanup(); }
  });

  it('creates nothing while automation is off or in dry-run', async () => {
    const s = await noticeScenario({ consent: true });
    try {
      await expire(s);
      await s.setAutomation({ automation_enabled: false });
      await reviewPrescriptions({ organizationId: s.orgId });
      await s.setAutomation({ automation_enabled: true, automation_dry_run: true });
      const dry = await reviewPrescriptions({ organizationId: s.orgId });
      expect(dry.dryRun).toBeGreaterThanOrEqual(1);
      expect(await counts(s)).toEqual({ incidents: 0, tasks: 0 });
    } finally { await s.cleanup(); }
  });
});

describe.skipIf(!enabled)('outbox cleanup', () => {
  it('drops old rows that never produced a notice and keeps sent ones', async () => {
    const s = await pending();
    try {
      const old = new Date(Date.now() - 60 * 86_400_000);
      await withTenant(s.orgId, (tx) => tx.outboxMessage.update({ where: { id: s.outbox.id }, data: { status: 'cancelled' } }));
      await withTenant(s.orgId, (tx) => tx.$executeRaw`UPDATE outbox_messages SET updated_at = ${old} WHERE id = ${s.outbox.id}`);
      const result = await cleanOutbox({ organizationId: s.orgId });
      expect(result.deleted).toBeGreaterThanOrEqual(1);
      expect(await withTenant(s.orgId, (tx) => tx.outboxMessage.count({ where: { id: s.outbox.id } }))).toBe(0);
    } finally { await s.cleanup(); }
  });
});

describe.skipIf(!enabled)('outbox endpoints', () => {
  it('lists, cancels a pending message and refuses to cancel a sent one', async () => {
    const s = await pending();
    try {
      const list = await s.agent.get('/api/v1/outbox?status=pending&limit=100').expect(200);
      const row = (list.body.data as { id: string; patient: { name: string } }[]).find((item) => item.id === s.outbox.id);
      expect(row).toBeTruthy();
      expect(JSON.stringify(row)).not.toContain('body');

      await s.agent.post(`/api/v1/outbox/${s.outbox.id}/cancel`).expect(200);
      expect((await s.reload()).status).toBe('cancelled');
      await s.agent.post(`/api/v1/outbox/${s.outbox.id}/cancel`).expect(409);
    } finally { await s.cleanup(); }
  });

  it('retries a failed message through the recovery marker, and not while another is queued', async () => {
    const s = await pending();
    try {
      await withTenant(s.orgId, (tx) => tx.outboxMessage.update({ where: { id: s.outbox.id }, data: { status: 'failed', lastError: 'interrupted' } }));
      const retried = await s.agent.post(`/api/v1/outbox/${s.outbox.id}/retry`).expect(200);
      expect(retried.body).toMatchObject({ status: 'pending', attempts: 0, last_error: 'manual_retry' });
      await s.agent.post(`/api/v1/outbox/${s.outbox.id}/retry`).expect(409);

      // The worker's next pass picks the marked message up and enqueues it.
      const { queue, jobs } = recordingQueue();
      await planNotices({ queue, now: insideWindow(), organizationId: s.orgId });
      expect(jobs.filter((job) => job.data.outboxId === s.outbox.id)).toHaveLength(1);
    } finally { await s.cleanup(); }
  });

  it('is limited by permission: viewing needs outbox:view, acting needs outbox:retry', async () => {
    const operator = await loginAs('operator');
    await operator.get('/api/v1/outbox').expect(403);
    await operator.post('/api/v1/outbox/x/cancel').expect(403);
    await operator.post('/api/v1/outbox/x/retry').expect(403);
    const readOnly = await loginAs('read_only');
    await readOnly.get('/api/v1/outbox').expect(403);
  });
});

describe.skipIf(!enabled)('kill-switch and pauses', () => {
  it('cancels pending messages at once and nothing is sent afterwards', async () => {
    const s = await pending();
    try {
      const response = await s.agent.post('/api/v1/automation/kill-switch').send({}).expect(200);
      expect(response.body.cancelled_messages).toBeGreaterThanOrEqual(1);
      const row = await s.reload();
      expect(row).toMatchObject({ status: 'cancelled', lastError: 'kill_switch' });
      const provider = new FakeProvider();
      const result = await sendNotice({ organizationId: s.orgId, outboxId: s.outbox.id, provider, queue: recordingQueue().queue, now: insideWindow() });
      expect(result.outcome).toBe('not_claimed');
      expect(provider.sent).toHaveLength(0);
      const { rows } = await s.plan();
      expect(rows.filter((item) => item.status === 'pending')).toHaveLength(0);
    } finally { await s.cleanup(); }
  });

  it('pausing a patient or a treatment cancels pending messages and stops new ones; resuming allows them again', async () => {
    const patient = await pending();
    try {
      const paused = await patient.agent.patch(`/api/v1/patients/${patient.patientId}/automation`).send({ paused: true, reason: 'Pidió esperar' }).expect(200);
      expect(paused.body).toMatchObject({ automationPaused: true, cancelled_messages: 1 });
      expect((await patient.reload()).status).toBe('cancelled');
      const after = await patient.plan();
      expect(after.rows.filter((row) => row.status === 'pending')).toHaveLength(0);
      await patient.agent.patch(`/api/v1/patients/${patient.patientId}/automation`).send({ paused: false }).expect(200);
      const resumed = await patient.plan();
      expect(resumed.rows.filter((row) => row.status === 'pending')).toHaveLength(1);
    } finally { await patient.cleanup(); }

    const treatment = await pending();
    try {
      const paused = await treatment.agent.patch(`/api/v1/treatments/${treatment.treatmentId}/automation`).send({ paused: true }).expect(200);
      expect(paused.body).toMatchObject({ automationPaused: true, cancelled_messages: 1 });
      const after = await treatment.plan();
      expect(after.rows.filter((row) => row.status === 'pending')).toHaveLength(0);
    } finally { await treatment.cleanup(); }
  });
});

describe.skipIf(!enabled)('exhausted attempts', () => {
  it('after the last attempt goes unanswered it creates one call task and one incident, once', async () => {
    const s = await noticeScenario({ consent: true });
    try {
      await s.setAutomation({ automation_enabled: true, automation_dry_run: false });
      // Three notices already went out, the last one two days ago, and the patient never answered.
      const outbox = await withTenant(s.orgId, (tx) => tx.outboxMessage.create({
        data: { organizationId: s.orgId, branchId: s.cycle.branchId, patientId: s.patientId, treatmentId: s.treatmentId, cycleId: s.cycle.id, templateId: s.templateId, channel: 'whatsapp', attemptNumber: 3, dedupeKey: `${s.cycle.id}:3:old${unique()}`, status: 'sent', scheduledFor: new Date(), sentAt: new Date(Date.now() - 2 * 86_400_000) },
      }));
      await withTenant(s.orgId, async (tx) => {
        await tx.notice.create({ data: { organizationId: s.orgId, outboxId: outbox.id, cycleId: s.cycle.id, patientId: s.patientId, mode: 'automatic', status: 'sent', attemptNumber: 3, sentAt: new Date(Date.now() - 2 * 86_400_000) } });
        await tx.refillCycle.update({ where: { id: s.cycle.id }, data: { status: 'notified', noticeAttempts: 3 } });
      });
      const { queue } = recordingQueue();
      await planNotices({ queue, now: insideWindow(), organizationId: s.orgId, onlyEscalations: true });
      await planNotices({ queue, now: insideWindow(), organizationId: s.orgId, onlyEscalations: true });
      await planNotices({ queue, now: insideWindow(), organizationId: s.orgId });
      const state = await withTenant(s.orgId, async (tx) => ({
        tasks: await tx.task.count({ where: { cycleId: s.cycle.id, type: 'call', status: 'open' } }),
        incidents: await tx.incident.findMany({ where: { cycleId: s.cycle.id, type: 'patient_no_response' } }),
      }));
      expect(state.tasks).toBe(1);
      expect(state.incidents).toHaveLength(1);
      expect(state.incidents[0]).toMatchObject({ autoGenerated: true, status: 'new' });

      // The «Sin respuesta» card now counts it.
      const dashboard = await s.agent.get('/api/v1/dashboard').expect(200);
      expect(dashboard.body.counts.no_response).toBeGreaterThanOrEqual(1);
      expect((dashboard.body.lists.no_response as unknown[]).length).toBeGreaterThanOrEqual(1);
      const card = await s.agent.get('/api/v1/dashboard/list?card=no_response').expect(200);
      expect(card.body.total).toBeGreaterThanOrEqual(1);
    } finally { await s.cleanup(); }
  });
});

describe.skipIf(!enabled)('conversation and unassigned replies', () => {
  it('shows notices and replies for a patient, audits the read, and needs outbox:view', async () => {
    const s = await pending();
    try {
      const sent = await sendNotice({ organizationId: s.orgId, outboxId: s.outbox.id, provider: new FakeProvider(), queue: recordingQueue().queue, now: insideWindow() });
      expect(sent.outcome).toBe('sent');
      await withTenant(s.orgId, (tx) => tx.whatsappInbound.create({
        data: { organizationId: s.orgId, providerMessageId: `wamid.conv${unique()}`, fromPhone: '18095550000', patientId: s.patientId, text: 'Gracias', receivedAt: new Date(insideWindow().getTime() + 1000), processedAt: new Date() },
      }));
      const response = await s.agent.get(`/api/v1/patients/${s.patientId}/messages`).expect(200);
      expect((response.body.data as { kind: string }[]).map((item) => item.kind)).toEqual(['reply', 'notice']);
      expect(response.body.data[0].text).toBe('Gracias');
      const audited = await withTenant(s.orgId, (tx) => tx.auditLog.count({ where: { action: 'patient.messages.read', subjectId: s.patientId } }));
      expect(audited).toBeGreaterThanOrEqual(1);
      const operator = await loginAs('operator');
      await operator.get(`/api/v1/patients/${s.patientId}/messages`).expect(403);
    } finally { await s.cleanup(); }
  });

  it('lets staff assign an unmatched reply to a patient, which then processes like any other', async () => {
    const s = await pending();
    try {
      const inbound = await withTenant(s.orgId, (tx) => tx.whatsappInbound.create({
        data: { organizationId: s.orgId, providerMessageId: `wamid.un${unique()}`, fromPhone: '18095559999', text: 'Hola, soy el hijo de la paciente', receivedAt: new Date(), processedAt: new Date() },
      }));
      const list = await s.agent.get('/api/v1/inbound/unassigned').expect(200);
      expect((list.body.data as { id: string }[]).map((row) => row.id)).toContain(inbound.id);

      await s.agent.post(`/api/v1/inbound/${inbound.id}/assign`).send({ patient_id: 'does-not-exist' }).expect(404);
      await s.agent.post(`/api/v1/inbound/${inbound.id}/assign`).send({ patient_id: s.patientId }).expect(200);
      const row = await withTenant(s.orgId, (tx) => tx.whatsappInbound.findFirstOrThrow({ where: { id: inbound.id } }));
      expect(row.patientId).toBe(s.patientId);
      expect(row.processedAt).not.toBeNull();
      const after = await s.agent.get('/api/v1/inbound/unassigned').expect(200);
      expect((after.body.data as { id: string }[]).map((item) => item.id)).not.toContain(inbound.id);
      await s.agent.post(`/api/v1/inbound/${inbound.id}/assign`).send({ patient_id: s.patientId }).expect(409);

      const operator = await loginAs('operator');
      await operator.post(`/api/v1/inbound/${inbound.id}/assign`).send({ patient_id: s.patientId }).expect(409);
    } finally { await s.cleanup(); }
  });

  it('read-only users cannot see or assign unmatched replies', async () => {
    const readOnly = await loginAs('read_only');
    await readOnly.get('/api/v1/inbound/unassigned').expect(403);
    await readOnly.post('/api/v1/inbound/x/assign').send({ patient_id: 'x' }).expect(403);
  });
});

