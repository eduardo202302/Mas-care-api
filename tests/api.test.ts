import { describe, expect, it } from 'vitest';
import request from 'supertest';
import { app } from '../src/app.js';
import { puede, permissionsFor } from '../src/domain/permissions.js';

describe('phase 0 API contract', () => {
  it('serves health and the generated OpenAPI document', async () => {
    expect((await request(app).get('/api/v1/health')).status).toBe(200);
    const document = (await request(app).get('/api/v1/openapi.json').expect(200)).body;
    expect(document.openapi).toBe('3.0.3');
    expect(document.paths['/api/v1/me']).toBeDefined();
    expect(document.paths['/api/v1/me'].get.responses['200']).toBeDefined();
    expect(document.paths['/api/v1/users'].get).toBeDefined();
    expect(document.paths['/api/v1/users'].post).toBeDefined();
    expect(document.paths['/api/v1/users/{id}'].get).toBeDefined();
    expect(document.paths['/api/v1/companies'].get).toBeDefined();
    expect(document.paths['/api/v1/companies'].post).toBeDefined();
    expect(document.paths['/api/v1/companies/{id}'].get).toBeDefined();
    expect(document.paths['/api/v1/companies/{id}'].patch).toBeDefined();
    expect(document.components.schemas.Company).toBeDefined();
    expect(document.components.schemas.CompanyDetail).toBeDefined();
    expect(document.paths['/api/v1/branches'].get.responses['200']).toBeDefined();
    expect(document.paths['/api/v1/branches'].post).toBeDefined();
    expect(document.paths['/api/v1/branches/{id}'].patch).toBeDefined();
    expect(document.paths['/api/v1/branches/{id}'].delete).toBeDefined();
    expect(document.paths['/api/v1/patients'].get).toBeDefined();
    expect(document.paths['/api/v1/patients'].post).toBeDefined();
    expect(document.paths['/api/v1/patients/check-duplicates'].post).toBeDefined();
    expect(document.paths['/api/v1/patients/{id}/caregivers'].get).toBeDefined();
    expect(document.paths['/api/v1/patients/{id}/caregivers'].post).toBeDefined();
    expect(document.paths['/api/v1/patients/{id}/consent'].post).toBeDefined();
    expect(document.paths['/api/v1/patients/{id}/activities'].get).toBeDefined();
    expect(document.paths['/api/v1/patients/{id}/activities'].post).toBeDefined();
    expect(document.paths['/api/v1/medications'].get).toBeDefined();
    expect(document.paths['/api/v1/medications'].post).toBeDefined();
    expect(document.paths['/api/v1/treatments'].get).toBeDefined();
    expect(document.paths['/api/v1/treatments'].post).toBeDefined();
    expect(document.paths['/api/v1/treatments/{id}/adjust-coverage'].post).toBeDefined();
    expect(document.paths['/api/v1/treatments/{id}/renew-prescription'].post).toBeDefined();
    expect(document.paths['/api/v1/settings'].get).toBeDefined();
    expect(document.paths['/api/v1/settings'].patch).toBeDefined();
    expect(document.paths['/api/v1/saved-views'].get).toBeDefined();
    expect(document.paths['/api/v1/saved-views'].post).toBeDefined();
    expect(document.paths['/api/v1/treatments/{id}/deliver'].post).toBeDefined();
    expect(document.paths['/api/v1/treatments/{id}/notice-preview'].get).toBeDefined();
    expect(document.paths['/api/v1/treatments/{id}/notice-logged'].post).toBeDefined();
    expect(document.paths['/api/v1/cycles/{id}/mark-prepared'].post).toBeDefined();
    expect(document.paths['/api/v1/cycles/{id}/mark-not-picked-up'].post).toBeDefined();
    expect(document.paths['/api/v1/dashboard'].get).toBeDefined();
    expect(document.paths['/api/v1/dashboard/list'].get).toBeDefined();
    expect(document.paths['/api/v1/tasks'].get).toBeDefined();
    expect(document.paths['/api/v1/tasks'].post).toBeDefined();
    expect(document.paths['/api/v1/tasks/{id}/complete'].post).toBeDefined();
    expect(document.paths['/api/v1/message-templates'].get).toBeDefined();
    expect(document.paths['/api/v1/message-templates'].post).toBeDefined();
    expect(document.paths['/api/v1/imports/patients/preview'].post).toBeDefined();
    expect(document.paths['/api/v1/imports/patients'].post).toBeDefined();
    expect(document.paths['/api/v1/board'].get).toBeDefined();
    expect(document.paths['/api/v1/board/columns/{status}'].get).toBeDefined();
    expect(document.paths['/api/v1/cycles'].get).toBeDefined();
    expect(document.paths['/api/v1/cycles/{id}/move'].post).toBeDefined();
    expect(document.paths['/api/v1/cycles/{id}/expected-on'].patch).toBeDefined();
    expect(document.paths['/api/v1/stock-marks'].get).toBeDefined();
    expect(document.paths['/api/v1/branches/{branchId}/stock-marks/{medicationId}'].put).toBeDefined();
    expect(document.paths['/api/v1/incidents'].get).toBeDefined();
    expect(document.paths['/api/v1/incidents'].post).toBeDefined();
    expect(document.paths['/api/v1/incidents/{id}'].get).toBeDefined();
    expect(document.paths['/api/v1/incidents/{id}'].patch).toBeDefined();
    expect(document.paths['/api/v1/incidents/{id}/move'].post).toBeDefined();
    expect(document.paths['/api/v1/incidents/{id}/resolve'].post).toBeDefined();
    expect(document.paths['/api/v1/patients/{id}/incidents'].get).toBeDefined();
    expect(document.components.securitySchemes.cookieAuth).toMatchObject({ type: 'apiKey', in: 'cookie' });
  });
  it('enforces the role matrix for branch management', () => {
    expect(puede('read_only', 'patients:write')).toBe(false);
    expect(puede('operator', 'branches:write')).toBe(false);
    expect(puede('owner', 'branches:write')).toBe(true);
    expect(puede('admin', 'branches:write')).toBe(true);
    expect(permissionsFor('read_only')).toContain('patients:read');
    expect(puede('operator', 'patients:archive')).toBe(false);
    expect(puede('operator', 'medications:write')).toBe(false);
    expect(puede('pharmacist', 'medications:write')).toBe(true);
    expect(puede('read_only', 'medications:read')).toBe(true);
    expect(puede('read_only', 'medications:write')).toBe(false);
    expect(puede('operator', 'tasks:write')).toBe(true);
    expect(puede('read_only', 'tasks:write')).toBe(false);
    expect(puede('pharmacist', 'templates:write')).toBe(true);
    expect(puede('operator', 'templates:write')).toBe(false);
    expect(puede('admin', 'imports:write')).toBe(true);
    expect(puede('pharmacist', 'imports:write')).toBe(false);
    expect(puede('read_only', 'dashboard:read')).toBe(true);
  });
  it('protects the branch list and does not trust a client tenant id', async () => {
    await request(app).get('/api/v1/branches?organization_id=another-tenant').expect(401);
    await request(app).get('/api/v1/users').expect(401);
  });
  it('returns field-level validation errors for registration input', async () => {
    const response = await request(app).post('/api/v1/register').send({ email: 'invalid' }).expect(400);
    expect(response.body.error.code).toBe('VALIDATION_ERROR');
    expect(response.body.error.fields).toHaveProperty('name');
  });
});
