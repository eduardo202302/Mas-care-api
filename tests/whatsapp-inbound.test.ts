import { insideWindow, noticeScenario, recordingQueue } from './helpers/notice-scenario.js';

const enabled = process.env.RUN_DB_TESTS === '1';
const APP_SECRET = 'test-app-secret';
const password = 'MaxCareDev-2026!';

const sign = (body: string) => `sha256=${createHmac('sha256', APP_SECRET).update(body).digest('hex')}`;
const unique = () => `${Date.now()}${Math.floor(Math.random() * 100000)}`;

type Msg = { id: string; from: string; text?: string; button?: 'confirm' | 'need_help'; context?: string };
const messagesPayload = (phoneNumberId: string, messages: Msg[]) => JSON.stringify({
  entry: [{ changes: [{ value: {
    metadata: { phone_number_id: phoneNumberId },
    messages: messages.map((m) => ({
      id: m.id, from: m.from, timestamp: String(Math.floor(Date.now() / 1000)),
      ...(m.button ? { type: 'button', button: { payload: m.button, text: m.button } } : { type: 'text', text: { body: m.text ?? '' } }),
      ...(m.context ? { context: { id: m.context } } : {}),
    })),
  } }] }],
});
const statusPayload = (phoneNumberId: string, id: string, status: string) => JSON.stringify({
  entry: [{ changes: [{ value: { metadata: { phone_number_id: phoneNumberId }, statuses: [{ id, status }] } }] }],
});
const post = (body: string, signature = sign(body)) =>
  request(app).post('/webhooks/whatsapp').set('Content-Type', 'application/json').set('X-Hub-Signature-256', signature).send(body);

/** A notified cycle whose patient received an automatic message, plus a WhatsApp number connected to the organization. */
async function notified() {
  const s = await noticeScenario({ consent: true });
  await s.setAutomation({ automation_enabled: true, automation_dry_run: false });
  const phoneNumberId = `9${unique()}`.slice(0, 15);
  await s.agent.put('/api/v1/automation/whatsapp-account').send({ phone_number_id: phoneNumberId, access_token: `EAAG${unique()}${unique()}` }).expect(200);
  const planned = await s.plan();
  const outbox = planned.rows[0]!;
  const sent = await sendNotice({ organizationId: s.orgId, outboxId: outbox.id, provider: new FakeProvider(), queue: recordingQueue().queue, now: insideWindow() });
  expect(sent.outcome).toBe('sent');
  const patient = await withTenant(s.orgId, (tx) => tx.patient.findFirstOrThrow({ where: { id: s.patientId } }));
  const from = patient.phone!.replace(/\D/g, '');
  const providerMessageId = (await withTenant(s.orgId, (tx) => tx.outboxMessage.findFirstOrThrow({ where: { id: outbox.id } }))).providerMessageId!;
  const cycleNow = () => withTenant(s.orgId, (tx) => tx.refillCycle.findFirstOrThrow({ where: { id: s.cycle.id } }));
  const notice = () => withTenant(s.orgId, (tx) => tx.notice.findFirstOrThrow({ where: { outboxId: outbox.id } }));
  const tasks = () => withTenant(s.orgId, (tx) => tx.task.findMany({ where: { patientId: s.patientId, autoGenerated: true } }));
  const inbound = () => withTenant(s.orgId, (tx) => tx.whatsappInbound.findMany({ where: { fromPhone: from } }));
  const receive = async (messages: Msg[]) => {
    await post(messagesPayload(phoneNumberId, messages)).expect(200);
    return processInbound({ organizationId: s.orgId });
  };
  const finish = async () => {
    await s.agent.delete('/api/v1/automation/whatsapp-account').expect(204);
    await s.cleanup();
  };
  return { ...s, phoneNumberId, from, providerMessageId, cycleNow, notice, tasks, inbound, receive, finish, outboxId: outbox.id };
}

describe.skipIf(!enabled)('WhatsApp webhook', () => {
  it('answers Meta\'s URL check only with the right token', async () => {
    const ok = await request(app).get('/webhooks/whatsapp').query({ 'hub.mode': 'subscribe', 'hub.verify_token': 'test-verify-token', 'hub.challenge': '12345' }).expect(200);
    expect(ok.text).toBe('12345');
    await request(app).get('/webhooks/whatsapp').query({ 'hub.mode': 'subscribe', 'hub.verify_token': 'wrong', 'hub.challenge': '12345' }).expect(403);
  });

  it('rejects a bad signature with 401 and stores nothing', async () => {
    const s = await notified();
    try {
      const body = messagesPayload(s.phoneNumberId, [{ id: `wamid.bad${unique()}`, from: s.from, text: 'hola' }]);
      await post(body, 'sha256=' + '0'.repeat(64)).expect(401);
      await post(body, '').expect(401);
      await request(app).post('/webhooks/whatsapp').set('Content-Type', 'application/json').send(body).expect(401);
      expect(await s.inbound()).toHaveLength(0);
    } finally { await s.finish(); }
  });

  it('stores a message once even when Meta delivers it twice, and updates delivery states forward only', async () => {
    const s = await notified();
    try {
      const body = messagesPayload(s.phoneNumberId, [{ id: `wamid.dup${unique()}`, from: s.from, text: 'hola' }]);
      await post(body).expect(200);
      await post(body).expect(200);
      expect(await s.inbound()).toHaveLength(1);

      await post(statusPayload(s.phoneNumberId, s.providerMessageId, 'read')).expect(200);
      expect((await s.notice()).status).toBe('read');
      await post(statusPayload(s.phoneNumberId, s.providerMessageId, 'delivered')).expect(200);
      expect((await s.notice()).status).toBe('read');
    } finally { await s.finish(); }
  });
});

describe.skipIf(!enabled)('processing replies', () => {
  it('moves the cycle to confirmed on the Confirm button and stops the chain, without sending anything', async () => {
    const s = await notified();
    try {
      const summary = await s.receive([{ id: `wamid.c${unique()}`, from: s.from, button: 'confirm' }]);
      expect(summary.confirmed).toBe(1);
      expect((await s.cycleNow()).status).toBe('confirmed');
      expect((await s.notice()).status).toBe('replied');
      expect((await s.outboxFor()).filter((row) => row.id !== s.outboxId)).toHaveLength(0);
      const [row] = await s.inbound();
      expect(row).toMatchObject({ patientId: s.patientId, cycleId: s.cycle.id });
      expect(row!.processedAt).not.toBeNull();
    } finally { await s.finish(); }
  });

  it('creates a call task on «Necesito hablar» and does not move the cycle', async () => {
    const s = await notified();
    try {
      await s.receive([{ id: `wamid.h${unique()}`, from: s.from, button: 'need_help' }]);
      expect((await s.cycleNow()).status).toBe('notified');
      const tasks = await s.tasks();
      expect(tasks.filter((task) => task.type === 'call')).toHaveLength(1);
    } finally { await s.finish(); }
  });

  it('saves free text, stops reminders and asks staff to review, without moving or answering', async () => {
    const s = await notified();
    try {
      const summary = await s.receive([{ id: `wamid.t${unique()}`, from: s.from, text: 'Mañana paso por la medicina, gracias' }]);
      expect(summary.free_text).toBe(1);
      expect((await s.cycleNow()).status).toBe('notified');
      expect((await s.notice()).status).toBe('replied');
      const tasks = await s.tasks();
      expect(tasks.map((task) => task.title)).toEqual([expect.stringContaining('Revisar respuesta')]);
      const [row] = await s.inbound();
      expect(row!.text).toContain('Mañana paso');
    } finally { await s.finish(); }
  });

  it('revokes consent on BAJA, cancels pending messages and asks staff to call', async () => {
    const s = await notified();
    try {
      // A second reminder is waiting to go out.
      await withTenant(s.orgId, (tx) => tx.outboxMessage.create({
        data: { organizationId: s.orgId, branchId: s.cycle.branchId, patientId: s.patientId, treatmentId: s.treatmentId, cycleId: s.cycle.id, templateId: s.templateId, channel: 'whatsapp', attemptNumber: 2, dedupeKey: `${s.cycle.id}:2:test${unique()}`, status: 'pending', scheduledFor: new Date() },
      }));
      const summary = await s.receive([{ id: `wamid.b${unique()}`, from: s.from, text: 'BAJA' }]);
      expect(summary.opt_out).toBe(1);
      const patient = await withTenant(s.orgId, (tx) => tx.patient.findFirstOrThrow({ where: { id: s.patientId } }));
      expect(patient.reminderConsent).toBe(false);
      const consents = await withTenant(s.orgId, (tx) => tx.patientConsent.findMany({ where: { patientId: s.patientId }, orderBy: { recordedAt: 'desc' } }));
      expect(consents[0]).toMatchObject({ granted: false, channel: 'whatsapp' });
      expect((await s.outboxFor()).filter((row) => row.status === 'pending')).toHaveLength(0);
      expect((await s.tasks()).filter((task) => task.type === 'call')).toHaveLength(1);
    } finally { await s.finish(); }
  });

  it('leaves a message unassigned when two patients of the organization share the number', async () => {
    const s = await notified();
    try {
      const patient = await withTenant(s.orgId, (tx) => tx.patient.findFirstOrThrow({ where: { id: s.patientId } }));
      await withTenant(s.orgId, (tx) => tx.patient.create({
        data: { organizationId: s.orgId, primaryBranchId: patient.primaryBranchId, fullName: 'Fictional Twin', phone: patient.phone, createdBy: patient.createdBy },
      }));
      const summary = await s.receive([{ id: `wamid.u${unique()}`, from: s.from, text: 'hola' }]);
      expect(summary.unassigned).toBe(1);
      const [row] = await s.inbound();
      expect(row!.patientId).toBeNull();
      expect((await s.cycleNow()).status).toBe('notified');
      expect(await s.tasks()).toHaveLength(0);
    } finally { await s.finish(); }
  });

  it('never assigns a reply to a patient of another organization with the same number', async () => {
    const s = await notified();
    try {
      // Same phone as a patient in organization A, but the message arrives on organization B's number.
      const agentA = request.agent(app);
      await agentA.post('/api/auth/sign-in/email').send({ email: 'owner.a@maxcare.test', password }).expect(200);
      const orgA = (await agentA.get('/api/v1/me').expect(200)).body as { organization: { id: string }; branches: { id: string }[] };
      const outsider = (await agentA.post('/api/v1/patients').send({ primaryBranchId: orgA.branches[0]!.id, fullName: `Fictional Outsider ${unique()}`, phone: '8095550199' }).expect(201)).body.patient as { id: string };
      const foreignPhone = '8095550199';
      await post(messagesPayload(s.phoneNumberId, [{ id: `wamid.x${unique()}`, from: `1${foreignPhone}`, text: 'hola' }])).expect(200);
      const summary = await processInbound({ organizationId: s.orgId });
      expect(summary.unassigned).toBe(1);
      const rows = await withTenant(s.orgId, (tx) => tx.whatsappInbound.findMany({ where: { fromPhone: `1${foreignPhone}` } }));
      expect(rows[0]!.patientId).toBeNull();
      const touched = await withTenant(orgA.organization.id, (tx) => tx.activity.count({ where: { patientId: outsider.id, type: 'notice' } }));
      expect(touched).toBe(0);
    } finally { await s.finish(); }
  });

  it('suppresses further reminders for a cycle whose patient replied', async () => {
    const s = await notified();
    try {
      await s.receive([{ id: `wamid.r${unique()}`, from: s.from, text: 'hola' }]);
      // Long after the retry period, the planner must still not queue a reminder.
      const later = new Date(insideWindow().getTime() + 3 * 86_400_000);
      const { queue } = recordingQueue();
      const { planNotices } = await import('../src/jobs/planNotices.js');
      await planNotices({ queue, now: later, organizationId: s.orgId });
      expect((await s.outboxFor()).filter((row) => row.attemptNumber > 1)).toHaveLength(0);
    } finally { await s.finish(); }
  });
});

describe.skipIf(!enabled)('WhatsApp account endpoint', () => {
  it('stores the token encrypted and never returns it', async () => {
    const s = await noticeScenario({ consent: false });
    try {
      const token = `EAAG-secret-${unique()}${unique()}`;
      const phoneNumberId = `8${unique()}`.slice(0, 15);
      const saved = await s.agent.put('/api/v1/automation/whatsapp-account').send({ phone_number_id: phoneNumberId, access_token: token }).expect(200);
      expect(JSON.stringify(saved.body)).not.toContain(token);
      const read = await s.agent.get('/api/v1/automation/whatsapp-account').expect(200);
      expect(read.body).toEqual({ connected: true, phone_number_id: phoneNumberId });
      const row = await withTenant(s.orgId, (tx) => tx.whatsappAccount.findFirstOrThrow());
      expect(row.accessTokenEnc).not.toContain(token);
      expect(row.accessTokenEnc.startsWith('v1:')).toBe(true);
      await s.agent.delete('/api/v1/automation/whatsapp-account').expect(204);
      expect((await s.agent.get('/api/v1/automation/whatsapp-account').expect(200)).body.connected).toBe(false);
    } finally { await s.cleanup(); }
  });

  it('only lets owners and admins manage it, and refuses a number already used by another organization', async () => {
    const operator = request.agent(app);
    await operator.post('/api/auth/sign-in/email').send({ email: 'operator.b@maxcare.test', password }).expect(200);
    await operator.get('/api/v1/automation/whatsapp-account').expect(403);
    await operator.put('/api/v1/automation/whatsapp-account').send({ phone_number_id: '12345678', access_token: 'x'.repeat(30) }).expect(403);

    const a = request.agent(app);
    await a.post('/api/auth/sign-in/email').send({ email: 'owner.a@maxcare.test', password }).expect(200);
    const b = request.agent(app);
    await b.post('/api/auth/sign-in/email').send({ email: 'owner.b@maxcare.test', password }).expect(200);
    const phoneNumberId = `7${unique()}`.slice(0, 15);
    try {
      await a.put('/api/v1/automation/whatsapp-account').send({ phone_number_id: phoneNumberId, access_token: 'a'.repeat(30) }).expect(200);
      await b.put('/api/v1/automation/whatsapp-account').send({ phone_number_id: phoneNumberId, access_token: 'b'.repeat(30) }).expect(409);
    } finally { await a.delete('/api/v1/automation/whatsapp-account'); }
  });
});
