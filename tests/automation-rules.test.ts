import './db-guard.js';
import { describe, expect, it } from 'vitest';
import request from 'supertest';
import { app } from '../src/app.js';
import { withTenant } from '../src/infra/prisma.js';

const enabled = process.env.RUN_DB_TESTS === '1';
const password = 'MaxCareDev-2026!';

async function login(role: string, organization = 'a') {
  const agent = request.agent(app);
  await agent.post('/api/auth/sign-in/email').send({ email: `${role}.${organization}@maxcare.test`, password }).expect(200);
  const context = (await agent.get('/api/v1/me').expect(200)).body as { organization: { id: string } };
  return { agent, context };
}

describe.skipIf(!enabled)('automation rules', () => {
  it('treatment_created: follow-up task with consent, call task without, nothing when a switch is off', async () => {
    const { agent, context } = await login('owner');
    const suffix = Date.now();
    const branch = (await agent.post('/api/v1/branches').send({ name: `Auto branch ${suffix}` }).expect(201)).body as { id: string };
    const medication = (await agent.post('/api/v1/medications').send({ genericName: `Fictional auto med ${suffix}`, presentation: '5 mg', unitsPerPackage: 30 }).expect(201)).body as { id: string };

    const treat = async (name: string, consent: boolean) => {
      const patient = (await agent.post('/api/v1/patients').send({ primaryBranchId: branch.id, fullName: name }).expect(201)).body.patient as { id: string };
      if (consent) await agent.post(`/api/v1/patients/${patient.id}/consent`).send({ granted: true, channel: 'whatsapp' }).expect(201);
      await agent.post('/api/v1/treatments').send({
        patient_id: patient.id, medication_id: medication.id, branch_id: branch.id, dose_per_intake: 1, intakes_per_day: 1,
        quantity_per_cycle: 30, start_date: new Date().toISOString().slice(0, 10),
      }).expect(201);
      return patient.id;
    };
    const tasksFor = (patientId: string) => withTenant(context.organization.id, (tx) => tx.task.findMany({ where: { patientId, autoGenerated: true } }));

    // Rule off + switch off: nothing created.
    const quiet = await treat(`Fictional quiet ${suffix}`, true);
    expect(await tasksFor(quiet)).toHaveLength(0);

    try {
    await agent.patch('/api/v1/automation/settings').send({ automation_enabled: true, automation_dry_run: false }).expect(200);
    await agent.patch('/api/v1/automation/rules/treatment_created').send({ enabled: true }).expect(200);

    const withConsent = await treat(`Fictional consent ${suffix}`, true);
    const noConsent = await treat(`Fictional noconsent ${suffix}`, false);
    expect((await tasksFor(withConsent)).map((t) => t.type)).toEqual(['other']);
    const call = await tasksFor(noConsent);
    expect(call.map((t) => t.type)).toEqual(['call']);
    expect(call[0]!.title).toContain('sin consentimiento');

    // Each run lands in the patient's history.
    const history = await withTenant(context.organization.id, (tx) => tx.activity.findMany({ where: { patientId: noConsent, type: 'automation' } }));
    expect(history).toHaveLength(1);

    } finally {
      await agent.patch('/api/v1/automation/rules/treatment_created').send({ enabled: false });
      await agent.patch('/api/v1/automation/settings').send({ automation_enabled: false, automation_dry_run: true });
    }
  });

  it('enroll requires the rule and the master switch to be on', async () => {
    const { agent } = await login('owner');
    const branch = (await agent.post('/api/v1/branches').send({ name: `Enroll branch ${Date.now()}` }).expect(201)).body as { id: string };
    const patient = (await agent.post('/api/v1/patients').send({ primaryBranchId: branch.id, fullName: 'Fictional enroll' }).expect(201)).body.patient as { id: string };
    await agent.patch('/api/v1/automation/rules/cycle_due_soon').send({ enabled: false }).expect(200);
    await agent.post('/api/v1/automation/rules/cycle_due_soon/enroll').send({ patientId: patient.id }).expect(409);
  });

  it('blocks non-managers from rules', async () => {
    const { agent } = await login('operator');
    await agent.get('/api/v1/automation/rules').expect(403);
  });
});
