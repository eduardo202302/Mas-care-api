import { currentBalance, isBelowThreshold } from '../domain/inventory.js';
import { logger } from '../infra/logger.js';
import { prisma, withTenant } from '../infra/prisma.js';
import { record } from '../modules/audit/record.js';
import { systemActor } from './shared.js';

export type InventoryAlertsSummary = { incidents: number };

/**
 * MVP scope only: low inventory raises one open `out_of_stock` Incident for
 * the team per treatment - reusing the existing incident type rather than a
 * new one, since it is the same "team needs to act on stock" concern the
 * pharmacy flow already has. Sending the patient a WhatsApp/email alert is
 * Phase 2 per the agreed plan (it needs a `low_inventory_patient`
 * MessageTemplate staff can configure first).
 */
export async function inventoryAlerts(options: { now?: Date; organizationId?: string } = {}): Promise<InventoryAlertsSummary> {
  const total: InventoryAlertsSummary = { incidents: 0 };
  const organizations = await prisma.organization.findMany({
    where: { status: 'active', ...(options.organizationId ? { id: options.organizationId } : {}) },
    select: { id: true },
  });
  for (const { id: organizationId } of organizations) {
    try {
      const summary = await withTenant(organizationId, async (tx) => {
        const out: InventoryAlertsSummary = { incidents: 0 };
        const treatments = await tx.treatment.findMany({
          where: { status: 'active', lowInventoryThreshold: { not: null } },
          select: { id: true, branchId: true, patientId: true, lowInventoryThreshold: true, patient: { select: { fullName: true } } },
          take: 2000,
        });
        if (!treatments.length) return out;
        const actorId = await systemActor(tx, organizationId);
        if (!actorId) return out;
        for (const treatment of treatments) {
          const entries = await tx.inventoryEntry.findMany({ where: { treatmentId: treatment.id }, select: { quantityDelta: true } });
          const balance = currentBalance(entries.map((entry) => ({ quantityDelta: entry.quantityDelta.toString() })));
          if (!isBelowThreshold(balance, treatment.lowInventoryThreshold!.toString())) continue;
          const links = { patientId: treatment.patientId, treatmentId: treatment.id };
          const existing = await tx.incident.findFirst({ where: { treatmentId: treatment.id, type: 'out_of_stock', status: { not: 'resolved' } }, select: { id: true } });
          if (existing) continue;
          const incident = await tx.incident.create({
            data: {
              organizationId, branchId: treatment.branchId, ...links, type: 'out_of_stock', status: 'new', autoGenerated: true,
              createdBy: actorId, description: `Inventario bajo: quedan ${balance} unidades para ${treatment.patient.fullName}`,
            },
          });
          await tx.activity.create({
            data: { organizationId, ...links, type: 'low_inventory_alert', body: 'Incidencia automática: inventario bajo', metadata: { incident_id: incident.id, balance, auto_generated: true }, authorId: actorId },
          });
          await record(tx, { organizationId, actorId, action: 'incident.auto_create', subjectId: incident.id, metadata: { type: 'out_of_stock' } });
          out.incidents += 1;
        }
        return out;
      });
      total.incidents += summary.incidents;
    } catch (error) {
      logger.error({ err: error, organizationId }, 'inventory alerts failed');
    }
  }
  return total;
}
