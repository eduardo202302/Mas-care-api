import { localDateString } from '../domain/localDate.js';
import { logger } from '../infra/logger.js';
import { prisma, withTenant } from '../infra/prisma.js';
import { record } from '../modules/audit/record.js';
import { effectiveSettings, systemActor } from './shared.js';

export type PrescriptionSummary = { incidents: number; tasks: number; dryRun: number };

/**
 * Daily: an active treatment whose prescription expired (by the organization's
 * own calendar) gets one open `prescription_expired` incident and one
 * `renew_prescription` task. Reruns never duplicate them. Follows the same
 * switches as notices: nothing is created while automation is off, and
 * dry-run only counts.
 */
export async function reviewPrescriptions(options: { now?: Date; organizationId?: string } = {}): Promise<PrescriptionSummary> {
  const now = options.now ?? new Date();
  const total: PrescriptionSummary = { incidents: 0, tasks: 0, dryRun: 0 };
  const organizations = await prisma.organization.findMany({
    where: { status: 'active', ...(options.organizationId ? { id: options.organizationId } : {}) },
    select: { id: true },
  });
  for (const { id: organizationId } of organizations) {
    try {
      const summary = await withTenant(organizationId, async (tx) => {
        const out: PrescriptionSummary = { incidents: 0, tasks: 0, dryRun: 0 };
        const orgSetting = await tx.setting.findFirst({ where: { branchId: null } });
        if (!orgSetting) return out;
        const treatments = await tx.treatment.findMany({
          where: { status: 'active', prescriptionExpiresOn: { not: null } },
          include: { patient: { select: { fullName: true, archivedAt: true } }, cycles: { where: { closedAt: null }, select: { id: true }, take: 1 } },
          take: 2000,
        });
        const actorId = await systemActor(tx, organizationId);
        for (const treatment of treatments) {
          const settings = await effectiveSettings(tx, treatment.branchId);
          if (!settings?.automationEnabled || treatment.patient.archivedAt) continue;
          const today = new Date(`${localDateString(now, settings.timezone)}T00:00:00.000Z`);
          if (!treatment.prescriptionExpiresOn || treatment.prescriptionExpiresOn > today) continue;
          if (settings.automationDryRun) { out.dryRun += 1; continue; }
          if (!actorId) continue;
          const links = { patientId: treatment.patientId, treatmentId: treatment.id, cycleId: treatment.cycles[0]?.id ?? null };
          const openIncident = await tx.incident.findFirst({ where: { treatmentId: treatment.id, type: 'prescription_expired', status: { not: 'resolved' } }, select: { id: true } });
          if (!openIncident) {
            const incident = await tx.incident.create({
              data: {
                organizationId, branchId: treatment.branchId, ...links, type: 'prescription_expired', status: 'new', autoGenerated: true,
                createdBy: actorId, description: 'La receta del tratamiento está vencida',
              },
            });
            await tx.activity.create({
              data: { organizationId, ...links, type: 'incident', body: 'Incidencia automática: receta vencida', metadata: { incident_id: incident.id, auto_generated: true }, authorId: actorId },
            });
            await record(tx, { organizationId, actorId, action: 'incident.auto_create', subjectId: incident.id, metadata: { type: 'prescription_expired' } });
            out.incidents += 1;
          }
          const openTask = await tx.task.findFirst({ where: { treatmentId: treatment.id, type: 'renew_prescription', status: 'open' }, select: { id: true } });
          if (!openTask) {
            await tx.task.create({
              data: {
                organizationId, branchId: treatment.branchId, ...links, type: 'renew_prescription', status: 'open', autoGenerated: true,
                title: `Renovar la receta de ${treatment.patient.fullName}`,
              },
            });
            out.tasks += 1;
          }
        }
        return out;
      });
      total.incidents += summary.incidents;
      total.tasks += summary.tasks;
      total.dryRun += summary.dryRun;
    } catch (error) {
      logger.error({ err: error, organizationId }, 'reviewing prescriptions failed');
    }
  }
  return total;
}

/** Retention for outbox rows that never produced a notice. Sent messages are kept: they are the history. */
export const OUTBOX_RETENTION_DAYS = 30;

/** Weekly: drops old dry-run, cancelled and failed outbox rows that have no notice attached. */
export async function cleanOutbox(options: { now?: Date; organizationId?: string } = {}): Promise<{ deleted: number }> {
  const cutoff = new Date((options.now ?? new Date()).getTime() - OUTBOX_RETENTION_DAYS * 86_400_000);
  let deleted = 0;
  const organizations = await prisma.organization.findMany({
    where: { status: 'active', ...(options.organizationId ? { id: options.organizationId } : {}) },
    select: { id: true },
  });
  for (const { id } of organizations) {
    const result = await withTenant(id, (tx) => tx.outboxMessage.deleteMany({
      where: { status: { in: ['dry_run', 'cancelled', 'failed'] }, updatedAt: { lt: cutoff }, notice: { is: null } },
    }));
    deleted += result.count;
  }
  return { deleted };
}
