import { logger } from '../infra/logger.js';
import { prisma, withTenant } from '../infra/prisma.js';
import { record } from '../modules/audit/record.js';
import { systemActor } from './shared.js';

export type DoseRemindersSummary = { tasks: number; incidents: number };

const TASK_AFTER_MS = 2 * 60 * 60 * 1000;
const INCIDENT_AFTER_MS = 24 * 60 * 60 * 1000;

/**
 * A `scheduled` dose is never auto-marked skipped (product decision: the
 * system never guesses a clinical fact nobody confirmed). The only
 * automatic behavior is escalation - one open follow-up Task per treatment
 * once a dose is 2h overdue, one open Incident once a dose is 24h overdue -
 * so the team notices without the DoseLog itself ever changing state on
 * its own.
 */
export async function doseReminders(options: { now?: Date; organizationId?: string } = {}): Promise<DoseRemindersSummary> {
  const now = options.now ?? new Date();
  const total: DoseRemindersSummary = { tasks: 0, incidents: 0 };
  const organizations = await prisma.organization.findMany({
    where: { status: 'active', ...(options.organizationId ? { id: options.organizationId } : {}) },
    select: { id: true },
  });
  for (const { id: organizationId } of organizations) {
    try {
      const summary = await withTenant(organizationId, async (tx) => {
        const out: DoseRemindersSummary = { tasks: 0, incidents: 0 };
        const taskCutoff = new Date(now.getTime() - TASK_AFTER_MS);
        const overdue = await tx.doseLog.findMany({
          where: { status: 'scheduled', scheduledFor: { lt: taskCutoff } },
          include: { treatment: { select: { id: true, branchId: true, patientId: true, patient: { select: { fullName: true } } } } },
          orderBy: { scheduledFor: 'asc' },
          take: 2000,
        });
        if (!overdue.length) return out;
        const actorId = await systemActor(tx, organizationId);
        if (!actorId) return out;
        const byTreatment = new Map<string, typeof overdue>();
        for (const doseLog of overdue) {
          const list = byTreatment.get(doseLog.treatmentId) ?? [];
          list.push(doseLog);
          byTreatment.set(doseLog.treatmentId, list);
        }
        for (const [treatmentId, logs] of byTreatment) {
          const treatment = logs[0]!.treatment;
          const links = { patientId: treatment.patientId, treatmentId };
          const oldestOverdueMs = now.getTime() - logs[0]!.scheduledFor.getTime();

          const existingTask = await tx.task.findFirst({ where: { treatmentId, type: 'dose_followup', status: 'open' }, select: { id: true } });
          if (!existingTask) {
            await tx.task.create({
              data: {
                organizationId, branchId: treatment.branchId, type: 'dose_followup', status: 'open', autoGenerated: true,
                ...links, title: `Registrar ${logs.length} toma(s) pendiente(s) de ${treatment.patient.fullName}`,
              },
            });
            out.tasks += 1;
          }

          if (oldestOverdueMs >= INCIDENT_AFTER_MS) {
            const existingIncident = await tx.incident.findFirst({ where: { treatmentId, type: 'dose_overdue', status: { not: 'resolved' } }, select: { id: true } });
            if (!existingIncident) {
              const incident = await tx.incident.create({
                data: {
                  organizationId, branchId: treatment.branchId, ...links, type: 'dose_overdue', status: 'new', autoGenerated: true,
                  createdBy: actorId, description: `${logs.length} toma(s) sin registrar por más de 24 horas`,
                },
              });
              await tx.activity.create({
                data: { organizationId, ...links, type: 'incident', body: 'Incidencia automática: tomas sin registrar', metadata: { incident_id: incident.id, auto_generated: true, count: logs.length }, authorId: actorId },
              });
              await record(tx, { organizationId, actorId, action: 'incident.auto_create', subjectId: incident.id, metadata: { type: 'dose_overdue' } });
              out.incidents += 1;
            }
          }
        }
        return out;
      });
      total.tasks += summary.tasks;
      total.incidents += summary.incidents;
    } catch (error) {
      logger.error({ err: error, organizationId }, 'dose reminders failed');
    }
  }
  return total;
}
