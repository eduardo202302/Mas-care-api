import { randomUUID } from 'node:crypto';
import type { Prisma } from '@prisma/client';
import { automationRuleCatalog, reminderTaskFor, type AutomationRuleKey } from '../../domain/automationRules.js';
import { findOrCreateSetting } from '../../infra/settings.js';
import { logger } from '../../infra/logger.js';
import { prisma, withTenant } from '../../infra/prisma.js';

type Tx = Prisma.TransactionClient;

export type RunSubject = { patientId: string; treatmentId?: string | null | undefined; cycleId?: string | null | undefined };
export type RunResult = { outcome: string; detail?: Record<string, unknown> };

const OPEN_STATUSES = ['to_notify', 'notified', 'confirmed', 'prepared'] as const;
const day = (date: Date) => date.toISOString().slice(0, 10);
const addDays = (date: Date, days: number) => new Date(date.getTime() + days * 86_400_000);
const num = (value: unknown, fallback: number) => (typeof value === 'number' && value > 0 ? value : fallback);

/**
 * Runs one rule for one subject. Nothing here contacts a patient: it only
 * creates internal tasks/incidents and writes the run into the history.
 * Outcomes other than `done` mean nothing was created.
 */
export async function runRule(
  tx: Tx,
  organizationId: string,
  key: AutomationRuleKey,
  subject: RunSubject,
  options: { manual?: boolean; actorId?: string } = {},
): Promise<RunResult> {
  const rule = await tx.automationRule.findFirst({ where: { key } });
  if (!rule?.enabled) return { outcome: 'rule_off' };
  const settings = await findOrCreateSetting(tx, organizationId, null);
  if (!settings.automationEnabled) return { outcome: 'disabled' };
  if (settings.automationDryRun) return { outcome: 'dry_run' };
  const actorId = options.actorId ?? rule.actorId;
  if (!actorId) return { outcome: 'no_actor' };

  const subjectKey = options.manual ? `manual:${randomUUID()}` : (subject.cycleId ?? subject.treatmentId ?? subject.patientId);
  if (!options.manual && await tx.automationRun.findFirst({ where: { ruleKey: key, subjectKey } })) return { outcome: 'already_ran' };

  const patient = await tx.patient.findFirst({ where: { id: subject.patientId, archivedAt: null } });
  if (!patient) return { outcome: 'patient_missing' };
  const treatment = subject.treatmentId
    ? await tx.treatment.findFirst({ where: { id: subject.treatmentId }, include: { medication: true } })
    : null;
  const cycle = subject.cycleId ? await tx.refillCycle.findFirst({ where: { id: subject.cycleId } }) : null;
  const medication = treatment?.medication;
  const medicationName = medication ? (medication.genericName ?? medication.brandName ?? medication.presentation) : 'tratamiento';
  const branchId = cycle?.branchId ?? treatment?.branchId ?? patient.primaryBranchId;
  const params = (rule.params ?? {}) as Record<string, unknown>;
  const links = { patientId: patient.id, treatmentId: treatment?.id ?? null, cycleId: cycle?.id ?? null };
  const createTask = (type: 'call' | 'other', title: string, dueAt?: Date) => tx.task.create({
    data: { organizationId, branchId, type, title, status: 'open', dueAt: dueAt ?? null, autoGenerated: true, ...links },
  });

  let detail: Record<string, unknown> = {};
  let summary = '';

  if (key === 'cycle_delivered') {
    if (!treatment) return { outcome: 'treatment_missing' };
    await createTask('other', `Entregado: ${medicationName} a ${patient.fullName}`);
    const open = await tx.refillCycle.findFirst({ where: { treatmentId: treatment.id, closedAt: null } });
    let nextCycleId = open?.id ?? null;
    if (!open && treatment.coverageEndOn) {
      const next = await tx.refillCycle.create({
        data: {
          organizationId, treatmentId: treatment.id, branchId: treatment.branchId, status: 'to_notify',
          expectedOn: treatment.coverageEndOn, expectedQuantity: treatment.quantityPerCycle,
          suggestedNoticeOn: addDays(treatment.coverageEndOn, -settings.noticeLeadDays),
        } as Prisma.RefillCycleUncheckedCreateInput,
      });
      nextCycleId = next.id;
    }
    detail = { next_cycle_id: nextCycleId };
    summary = 'Equipo avisado y siguiente ciclo verificado';
  } else if (key === 'treatment_created') {
    const followUp = reminderTaskFor(patient.reminderConsent, patient.fullName, `seguimiento de ${medicationName}`);
    await createTask(followUp.type, followUp.title, addDays(new Date(), num(params.followUpDays, 7)));
    detail = { without_consent: followUp.withoutConsent };
    summary = 'Tarea de seguimiento creada';
  } else if (key === 'cycle_due_soon') {
    if (!cycle) return { outcome: 'cycle_missing' };
    const reminder = reminderTaskFor(patient.reminderConsent, patient.fullName, `${medicationName} vence el ${day(cycle.expectedOn)}`);
    await createTask(reminder.type, reminder.title, cycle.expectedOn);
    detail = { without_consent: reminder.withoutConsent };
    summary = 'Recordatorio creado';
  } else {
    if (!cycle) return { outcome: 'cycle_missing' };
    const existing = await tx.incident.findFirst({ where: { cycleId: cycle.id, type: 'patient_no_response', status: { not: 'resolved' } } });
    if (existing) return { outcome: 'incident_exists' };
    const incident = await tx.incident.create({
      data: {
        organizationId, branchId, patientId: patient.id, treatmentId: treatment?.id ?? null, cycleId: cycle.id,
        type: 'patient_no_response', status: 'new', createdBy: actorId,
        description: `Sin respuesta tras ${num(params.days, 3)} días (${medicationName})`,
      },
    });
    detail = { incident_id: incident.id };
    summary = 'Incidencia «Sin respuesta» creada';
  }

  await tx.automationRun.create({
    data: { organizationId, ruleKey: key, subjectKey, ...links, manual: Boolean(options.manual), outcome: 'done', detail: detail as Prisma.InputJsonObject },
  });
  await tx.activity.create({
    data: {
      organizationId, patientId: patient.id, treatmentId: treatment?.id ?? null, cycleId: cycle?.id ?? null,
      type: 'automation', body: `${automationRuleCatalog[key].label}: ${summary}`,
      metadata: { rule: key, manual: Boolean(options.manual), ...detail } as Prisma.InputJsonObject, authorId: actorId,
    },
  });
  return { outcome: 'done', detail };
}

/** Hook for event-driven rules. Never lets an automation failure break the user's action. */
export async function fireEvent(tx: Tx, organizationId: string, key: AutomationRuleKey, subject: RunSubject) {
  try {
    await tx.$executeRaw`SAVEPOINT automation_event`;
    const result = await runRule(tx, organizationId, key, subject);
    await tx.$executeRaw`RELEASE SAVEPOINT automation_event`;
    return result;
  } catch (error) {
    await tx.$executeRaw`ROLLBACK TO SAVEPOINT automation_event`;
    logger.warn({ err: error, key }, 'automation event failed');
    return { outcome: 'error' } satisfies RunResult;
  }
}

/** Time-based rules (Vence pronto, Sin respuesta) for one organization. */
export async function runScheduledForOrganization(organizationId: string) {
  const subjects = await withTenant(organizationId, async (tx) => {
    const rules = await tx.automationRule.findMany({ where: { enabled: true } });
    const settings = await findOrCreateSetting(tx, organizationId, null);
    if (!rules.length || !settings.automationEnabled || settings.automationDryRun) return [];
    const today = new Date(`${day(new Date())}T00:00:00.000Z`);
    const found: { key: AutomationRuleKey; subject: RunSubject }[] = [];
    const select = { id: true, treatment: { select: { id: true, patientId: true } } } as const;
    if (rules.some((r) => r.key === 'cycle_due_soon')) {
      const cycles = await tx.refillCycle.findMany({
        where: { closedAt: null, status: { in: [...OPEN_STATUSES] }, expectedOn: { gte: today, lte: addDays(today, settings.dueSoonDays) } },
        select, take: 500,
      });
      for (const c of cycles) found.push({ key: 'cycle_due_soon', subject: { patientId: c.treatment.patientId, treatmentId: c.treatment.id, cycleId: c.id } });
    }
    const noResponse = rules.find((r) => r.key === 'cycle_no_response');
    if (noResponse) {
      const days = num((noResponse.params as Record<string, unknown>).days, 3);
      // shortcut: cycle.updatedAt stands in for "notified at"; any later edit restarts the clock. Upgrade if it hides real no-response cases.
      const cycles = await tx.refillCycle.findMany({
        where: { closedAt: null, status: 'notified', updatedAt: { lte: addDays(new Date(), -days) } },
        select, take: 500,
      });
      for (const c of cycles) found.push({ key: 'cycle_no_response', subject: { patientId: c.treatment.patientId, treatmentId: c.treatment.id, cycleId: c.id } });
    }
    return found;
  });
  let created = 0;
  for (const { key, subject } of subjects) {
    try {
      const result = await withTenant(organizationId, (tx) => runRule(tx, organizationId, key, subject));
      if (result.outcome === 'done') created += 1;
    } catch (error) {
      logger.warn({ err: error, key, organizationId }, 'scheduled automation failed');
    }
  }
  return created;
}

export async function runScheduledAutomations() {
  const organizations = await prisma.organization.findMany({ where: { status: 'active' }, select: { id: true } });
  for (const { id } of organizations) {
    try { await runScheduledForOrganization(id); } catch (error) { logger.warn({ err: error, organizationId: id }, 'automation sweep failed'); }
  }
}
